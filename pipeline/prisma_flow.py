#!/usr/bin/env python3
"""Write docs/prisma_flow.md: the PRISMA 2020 flow counts of the updated review.

Reads data/counts.tex (every macro the article uses) and data/prisma_counts.json (exclusion codes and the data
date). Run from the repository root after pipeline/make_counts.py; `make counts` runs both. Each number is printed
with the name of the LaTeX macro that carries it into the article, so the table can be checked against the
article's flow diagram. The output depends only on the two input files.
"""
import json
import os
import re

macros = dict(re.findall(r'\\newcommand\{\\(\w+)\}\{([^}]*)\}', open('data/counts.tex', encoding='utf-8').read()))
counts = json.load(open('data/prisma_counts.json', encoding='utf-8'))


def cell(name):
    if name is None:
        return ''
    v = macros.get(name)
    return '(missing)' if v is None else f'{v} `{name}`'


def codes(d):
    return '; '.join(f'{k} {v}' for k, v in sorted(d.items(), key=lambda kv: (-kv[1], kv[0]))) or 'none'


ORIGINAL = [
    ('Records identified: OUCI database search', 'nOuciRecords'),
    ('Records identified: citation chaining', 'nChaining'),
    ('Reports sought for retrieval', 'nSought'),
    ('Reports not retrieved (no open-access full text: original criterion E7)', 'nNotRetrieved'),
    ('Reports assessed for eligibility', 'nAssessedFT'),
    ('Reports excluded', 'nExcludedFT'),
    ('Studies included', 'nIncluded'),
]
# stage, Scopus, OUCI re-run, both databases, the 31 originally unretrieved records re-sought
UPDATE = [
    ('Records identified', 'nScopusRecords', 'nOuciRerunRecords', None, None),
    ('Removed before screening: already in the original review', 'nScopusOverlapOuci', 'nOuciRerunDupOrig', None, None),
    ('Removed before screening: also found in Scopus', None, 'nOuciRerunDupScopus', None, None),
    ('Records screened (title and abstract)', 'nScopusScreened', 'nOuciRerunNew', 'nUpdateScreened', None),
    ('Records excluded at title and abstract', 'nScopusTAExcluded', 'nOuciRerunTAExcluded', 'nUpdateTAExcluded', None),
    ('Reports sought for retrieval', 'nScopusSought', 'nOuciRerunSought', 'nUpdateSought', 'nNoOAReSought'),
    ('Reports not retrieved (amended criterion E7)', 'nScopusNotRetrieved', 'nOuciRerunNotRetrieved',
     'nUpdateNotRetrieved', 'nNoOANotRetrieved'),
    ('Reports assessed for eligibility', 'nScopusAssessed', 'nOuciRerunAssessed', 'nUpdateAssessed', 'nNoOAAssessed'),
    ('Reports excluded', 'nScopusFTExcluded', 'nOuciRerunFTExcluded', 'nUpdateFTExcluded', 'nNoOAFTExcluded'),
    ('Studies included', 'nScopusIncluded', 'nOuciRerunIncluded', 'nUpdateIncludedDB', 'nNoOAIncluded'),
]
TOTALS = [
    ('Studies included by the update', 'nUpdateIncluded'),
    ('Studies included in the review (original and update)', 'nIncludedTotal'),
    ('Records still awaiting a decision (never counted as included)', 'nUpdatePending'),
    ('Reports not retrieved at the cut-off (update and re-sought records)', 'nResidualNotRetrieved'),
    ('Full texts obtained by automated open-access retrieval', 'nFTAuto'),
    ('Full texts obtained by the review team by hand (library access, or open-access copies the automated retrieval had not reached)', 'nFTManual'),
    ('Included studies that report a sample size', 'nReportN'),
    ('Included studies that report an effect size', 'nReportEffectSize'),
    ('Included studies these two rows refer to', 'nReportBase'),
    ('Originally included studies re-read under the update rules', 'nOrigSensitivityJudged'),
    ('... of which meet the update rules', 'nOrigMeetUpdateRules'),
]

out = ['# PRISMA 2020 flow of the updated review: counts', '',
       'Generated by `pipeline/prisma_flow.py` from `data/counts.tex` and `data/prisma_counts.json` '
       f'(data as of {counts.get("generated", "unknown")}). Do not edit by hand: run `make counts`.',
       'Each number is followed by the name of the LaTeX macro that carries it into the article.', '',
       '## Original review (OUCI, searched January 2026; decisions as made then)', '',
       '| Stage | Count |', '|---|---|']
out += [f'| {label} | {cell(m)} |' for label, m in ORIGINAL]
out += ['', '## Update (searched November 2026)', '',
        'Screening and eligibility decisions of the update were made by two language models (a first pass and a '
        'second-reading adjudication) without author verification; see `prompts/`.', '',
        '| Stage | Scopus | OUCI re-run | Both databases | Other methods: originally unretrieved records, re-sought |',
        '|---|---|---|---|---|']
out += [f'| {label} | {cell(s)} | {cell(o)} | {cell(b)} | {cell(n)} |' for label, s, o, b, n in UPDATE]
out += ['', 'Exclusion codes: E1-E7 and NOREL, NONEMP, NOIND, OFF, defined in `prompts/01_title_abstract_first_pass.md`, '
        '`prompts/03_fulltext_assessment.md` and `prompts/03b_fulltext_decision_rules.md`.', '',
        f'- Title/abstract exclusions by code: {codes(counts.get("taExcludedByCode", {}))}',
        f'- Full-text exclusions by code (update and re-sought records): {codes(counts.get("ftExcludedByCode", {}))}',
        '', '## Totals and reporting', '', '| Item | Count |', '|---|---|']
out += [f'| {label} | {cell(m)} |' for label, m in TOTALS]
os.makedirs('docs', exist_ok=True)
open('docs/prisma_flow.md', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
