#!/usr/bin/env python3
"""Compare a regenerated output file with a reference copy.

Usage: python3 tests/compare_outputs.py KIND OUTPUT REFERENCE
KIND   bytes  exact comparison
       tex    counts.tex: only the generator path in '%% GENERATED by <path>' and the stamp in '%% generated <stamp>;'
              are normalised; every other character, including every macro line, must be identical
       json   prisma_counts.json: only the value of "generated" is normalised
       s3     S3_search_strategies.md: only the date in 'Generated <date> ' is normalised
Exit status 0 when the files are identical after normalisation, 1 otherwise.
"""
import re
import sys

NORM = {
    'tex': lambda t: re.sub(r'^(%% generated )[^;\n]+', r'\1<generated>',
                            re.sub(r'^(%% GENERATED by )\S+', r'\1<generator>', t, flags=re.M), flags=re.M),
    'json': lambda t: re.sub(r'("generated": )"[^"]*"', r'\1"<generated>"', t),
    's3': lambda t: re.sub(r'^Generated \d{4}-\d{2}-\d{2} ', 'Generated <date> ', t, flags=re.M),
}


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ('bytes', *NORM):
        sys.exit(__doc__)
    kind, out, ref = sys.argv[1:]
    a, b = open(out, 'rb').read(), open(ref, 'rb').read()
    if kind != 'bytes':
        a, b = NORM[kind](a.decode('utf-8')), NORM[kind](b.decode('utf-8'))
    if a == b:
        print(f'PASS {kind:5} {out}')
        return 0
    print(f'FAIL {kind:5} {out} differs from {ref}')
    if kind != 'bytes':
        al, bl = a.splitlines(), b.splitlines()
        for x, y in [(x, y) for x, y in zip(al, bl) if x != y][:5]:
            print(f'   output:    {x}\n   reference: {y}')
        if len(al) != len(bl):
            print(f'   lines: output {len(al)}, reference {len(bl)}')
    return 1


if __name__ == '__main__':
    sys.exit(main())
